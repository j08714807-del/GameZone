export const getFeaturedGames = () => games.filter(g => g.isFeatured);
export const getNewReleases = () => games.filter(g => g.isNew);
export const getOnSaleGames = () => games.filter(g => g.isOnSale && g.discount > 0);
export const getGameById = (id) => games.find(g => g.id === parseInt(id));
export const getGameBySlug = (slug) => games.find(g => g.slug === slug);
export const getGamesByCategory = (category) => 
  category === 'All' ? games : games.filter(g => g.category === category);
export const searchGames = (query) => 
  games.filter(g => g.title.toLowerCase().includes(query.toLowerCase()));
